import { lstat, mkdir, mkdtemp, open as openFile, readdir, rename, rm, writeFile } from "node:fs/promises";
import { constants } from "node:fs";
import { basename, dirname, join, resolve } from "node:path";
import { randomUUID } from "node:crypto";
import { CliError } from "../errors.ts";
import { expectOk, serverCommand } from "../server.ts";
import type { Ui } from "../ui.ts";
import { open } from "./shared.ts";
import { starterPage } from "./starter-page.ts";

const maxFile = 256 * 1024;
const marker = "# Generated from index.html by your-space app pack.\n";

async function source(path: string, limit = maxFile): Promise<string> {
  try {
    const f = await openFile(path, constants.O_RDONLY | constants.O_NOFOLLOW | constants.O_NONBLOCK);
    try {
      const stat = await f.stat();
      if (!stat.isFile() || stat.size > limit) throw new Error();
      const buffer = Buffer.alloc(limit + 1);
      let n = 0;
      while (n <= limit) {
        const { bytesRead } = await f.read(buffer, n, buffer.length - n, null);
        if (!bytesRead) break;
        n += bytesRead;
      }
      if (n > limit) throw new Error();
      return new TextDecoder("utf-8", { fatal: true }).decode(buffer.subarray(0, n));
    } finally {
      await f.close();
    }
  } catch {
    throw new CliError("invalid_input", "Expected a regular UTF-8 " + basename(path) + " within the file size limit.");
  }
}

function composeFromPage(html: string) {
  // A conventional Compose project. Node serves one immutable document from memory;
  // the image needs no writeable host directory, registry account or local image build.
  const serve = [
    "const http = require('node:http');",
    "const page = Buffer.from(process.env.PAGE_BASE64, 'base64');",
    "http.createServer((req, res) => {",
    "  if (req.url.split('?')[0] !== '/' || !['GET', 'HEAD'].includes(req.method)) { res.writeHead(404); res.end(); return; }",
    "  res.writeHead(200, {'content-type':'text/html; charset=utf-8','x-content-type-options':'nosniff','cache-control':'no-cache'});",
    "  res.end(req.method === 'HEAD' ? undefined : page);",
    "}).listen(8080, '0.0.0.0');",
  ].join("\n");
  return (
    marker +
    JSON.stringify(
      {
        services: {
          web: {
            image: "node:26-slim",
            user: "node",
            read_only: true,
            command: ["node", "-e", serve],
            environment: { PAGE_BASE64: Buffer.from(html).toString("base64") },
            expose: ["8080"],
          },
        },
      },
      null,
      2,
    ) +
    "\n"
  );
}

export async function newApp(ui: Ui, folder: string) {
  const destination = resolve(folder),
    name = basename(destination);
  if (!/^[a-z][a-z0-9-]{0,29}$/.test(name))
    throw new CliError(
      "invalid_input",
      "Use a directory name starting with a lowercase letter, up to 30 lowercase letters, digits and hyphens.",
    );
  const existing = await lstat(destination).catch((error: NodeJS.ErrnoException) => {
    if (error.code !== "ENOENT") throw error;
  });
  if (existing && (!existing.isDirectory() || (await readdir(destination)).length))
    throw new CliError("folder_not_empty", "Choose a new or empty app directory.");
  await mkdir(dirname(destination), { recursive: true });
  const stage = await mkdtemp(join(dirname(destination), ".ys-app-"));
  try {
    const title = name
      .split("-")
      .filter(Boolean)
      .map((word) => word[0].toUpperCase() + word.slice(1))
      .join(" ");
    const html = starterPage(title);
    await writeFile(join(stage, "index.html"), html);
    await writeFile(
      join(stage, "kit.yaml"),
      [
        "kit: 1",
        "name: " + name,
        "title: " + JSON.stringify(title),
        "interface:",
        "  service: web",
        "  port: 8080",
        "pane: true",
        "",
      ].join("\n"),
    );
    await writeFile(join(stage, "compose.yaml"), composeFromPage(html));
    await rename(stage, destination);
  } finally {
    await rm(stage, { recursive: true, force: true });
  }
  ui.result({ folder: destination, name, files: ["index.html", "compose.yaml", "kit.yaml"] }, () =>
    ui.outro("Edit index.html, then run your-space app pack " + JSON.stringify(folder) + "."),
  );
}

export async function packApp(ui: Ui, folder: string) {
  const dest = join(resolve(folder), "compose.yaml");
  // Protect an author's existing hand-written Compose file.
  const exists = await lstat(dest).catch((error: NodeJS.ErrnoException) => {
    if (error.code !== "ENOENT") throw error;
  });
  if (exists && !(await source(dest)).startsWith(marker))
    throw new CliError("invalid_input", "This compose.yaml was not generated by app pack.");
  const output = composeFromPage(await source(join(resolve(folder), "index.html"), 64 * 1024));
  const tmp = dest + "." + randomUUID();
  try {
    await writeFile(tmp, output, { flag: "wx" });
    await rename(tmp, dest);
  } finally {
    await rm(tmp, { force: true });
  }
  ui.result({ compose: dest }, () => ui.outro("Packed " + dest));
}

export async function installLocalApp(ui: Ui, workdir: string, folder: string) {
  const root = resolve(folder);
  const composeText = await source(join(root, "compose.yaml"));
  const kitText = await source(join(root, "kit.yaml"));
  const { compose } = await open(ui, workdir, true);
  const report = expectOk(
    await serverCommand(
      compose,
      "install-app",
      ["--files-stdin"],
      JSON.stringify({ compose: composeText, kit: kitText }),
    ),
  );
  const { ok: _ok, ...body } = report;
  ui.result(body, () => ui.outro("Installed " + String(report.name) + " at " + String(report.origin)));
}
