// Prints the two platform secrets and where each comes from (contracts/operator-commands.md):
//   docker compose exec server show-secrets [--json]
// For owners who want to keep the generated values in their own password manager, or move them
// into .env. Prints to the terminal only; nothing is logged.
import { SECRETS, resolveSecret, SECRETS_DIR, type Source } from "../secrets.ts";
import { EXIT, output } from "./output.ts";

export interface ShownSecret {
  name: string;
  label: string;
  source: Source;
  value: string;
}

/** The secrets in use, or the settings that have none yet. */
export function describeSecrets(env: NodeJS.ProcessEnv, dir: string = SECRETS_DIR): { shown: ShownSecret[]; missing: string[] } {
  const shown: ShownSecret[] = [];
  const missing: string[] = [];
  for (const spec of SECRETS) {
    const resolved = resolveSecret(spec, env, dir);
    if (resolved) shown.push({ name: spec.env, label: spec.label, ...resolved });
    else missing.push(spec.env);
  }
  return { shown, missing };
}

const SOURCE_TEXT: Record<Source, string> = { env: "set in .env", generated: "generated by Your Space" };

if (import.meta.main) {
  const args = process.argv.slice(2);
  const json = args.includes("--json");
  const out = output(json);
  const unknown = args.filter((arg) => arg !== "--json");
  if (unknown.length > 0) {
    out.failure({ ok: false, error: "usage", message: `Unknown argument: ${unknown[0]}` }, `Unknown argument: ${unknown[0]}\nUsage: show-secrets [--json]`);
    process.exit(EXIT.usage);
  }
  const { shown, missing } = describeSecrets(process.env);
  if (missing.length > 0) {
    const message = `No value yet for ${missing.join(" and ")}. Start Your Space with docker compose up -d, which generates it.`;
    out.failure({ ok: false, error: "unexpected", message }, message);
    process.exit(EXIT.unexpected);
  }
  out.success(
    { ok: true, secrets: shown.map(({ name, source, value }) => ({ name, source, value })) },
    // A generated secret uses only letters, digits, - and _, so its line can be copied into .env as
    // it is. A secret set in .env is printed as Your Space reads it, which may differ from how .env
    // writes it (quoted, or with $$ for $).
    [
      ...shown.flatMap(({ name, label, source, value }) => [`# ${label}, ${SOURCE_TEXT[source]}`, `${name}=${value}`]),
      "# Keep these private. To manage a generated one yourself, copy its line into .env; Your Space then uses .env.",
    ],
  );
}
